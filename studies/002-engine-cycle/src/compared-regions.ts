/**
 * Writes the list of J47 test regions the engine carries to decide between
 * "validated" and "estimated". The list is generated from the comparison, never
 * typed: packages/physics/test/propulsion/j47.test.ts checks it against a fresh one.
 */

import type { J47Comparison } from "../../../packages/physics/src/propulsion/j47-comparison.ts";

export function renderComparedRegions(comparison: J47Comparison): string {
  const rows = comparison.regions.map(
    (r) =>
      `  { id: ${JSON.stringify(r.region.id)}, mach: ${r.region.mach}, ambientPressure_Pa: ${r.region.ambientPressure_Pa}, ` +
      `ambientTemperature_K: ${r.region.ambientTemperature_K}, maxSpeedFraction: ${r.region.maxSpeedFraction}, ` +
      `scoredPoints: ${r.points.length}, compared: ${r.compared}, hit: ${r.hit} },`,
  );
  return `/**
 * GENERATED by studies/002-engine-cycle/run.ts from the comparison of the anchored
 * model with NACA RM E9G09, table I. Do not edit by hand.
 *
 * One entry per test region with at least one run above 85 percent of rated speed.
 * The centre is the mean of the measured flight Mach number, tunnel static pressure
 * and equivalent ambient temperature of those runs. \`compared\` and \`hit\` follow the
 * criterion of studies/002-engine-cycle/PLAN.md, section 6.
 */

import type { RegionCentre } from "./j47-regions.ts";

export interface ComparedRegion extends RegionCentre {
  /** Scored points: runs above 85 percent of rated speed, without the anchor run */
  readonly scoredPoints: number;
  readonly compared: boolean;
  readonly hit: boolean;
}

export const J47_COMPARED_REGIONS: readonly ComparedRegion[] = [
${rows.join("\n")}
];
`;
}
